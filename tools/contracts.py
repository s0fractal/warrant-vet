"""SPEC, contracts and mutants — one checker.

    python3 tools/contracts.py spec      # write SPEC.md from the ADRs' Normative sections
    python3 tools/contracts.py check     # SPEC fresh; every statement has a contract,
                                         # the contract quotes it exactly, witnesses <-> tests,
                                         # every mutant named exists
    python3 tools/contracts.py mutate [ID...]  # every mutant must fail a witness of its own statement

A statement lives in exactly one ADR, as `- **WVET-XX.** text`. Its contract
(contracts/WVET-XX.json) quotes it, names the tests that witness it (each such
test says `witness: WVET-XX` in its docstring, and every test that says so is
named), names the mutants that must be killed, and keeps an append-only history
of why the statement reads as it does."""
import ast
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADR = ROOT / "docs" / "adr"
SPEC = ROOT / "SPEC.md"
CONTRACTS = ROOT / "contracts"
MUTANTS = ROOT / "tools" / "mutants.json"
STATEMENT = re.compile(r"^- \*\*(WVET-[A-Z]\d+)\.\*\* (.+)$", re.M)


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def statements():
    out = {}
    for adr in sorted(ADR.glob("*.md")):
        text = adr.read_text(encoding="utf-8")
        normative = text.split("## Normative", 1)[1].split("\n## ", 1)[0] if "## Normative" in text else ""
        title = text.splitlines()[0].lstrip("# ")
        for sid, stmt in STATEMENT.findall(normative):
            if sid in out:
                sys.exit(f"{sid} stated twice")
            out[sid] = (adr, title, stmt)
    return out


def render_spec():
    lines = ["# warrant-vet/0 — specification", "",
             "Generated by `python3 tools/contracts.py spec` from the Normative sections of",
             "[docs/adr/](docs/adr/). Do not edit; change the ADR. Each statement links its",
             "contract (witness tests, mutants, history).", ""]
    current = None
    for sid, (adr, title, stmt) in statements().items():
        if adr != current:
            current = adr
            lines += ["", f"## [{title}](docs/adr/{adr.name})", ""]
        lines.append(f"- **{sid}** ([contract](contracts/{sid}.json)). {stmt}")
    return "\n".join(lines) + "\n"


def witnesses_in_tests():
    found = {}
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                for sid in re.findall(r"witness: (WVET-[A-Z]\d+)", ast.get_docstring(node) or ""):
                    found.setdefault(sid, set()).add(node.name)
    return found


def check():
    errors = []
    if not SPEC.is_file() or SPEC.read_text(encoding="utf-8") != render_spec():
        errors.append("SPEC.md is stale: run python3 tools/contracts.py spec")
    stmts, tests = statements(), witnesses_in_tests()
    mutants = {m["id"]: m for m in json.loads(MUTANTS.read_text(encoding="utf-8"))}
    named = set()
    for sid, (adr, _, stmt) in stmts.items():
        path = CONTRACTS / f"{sid}.json"
        if not path.is_file():
            errors.append(f"{sid}: no contract")
            continue
        c = json.loads(path.read_text(encoding="utf-8"))
        if c.get("statement") != stmt or c.get("adr") != f"docs/adr/{adr.name}":
            errors.append(f"{sid}: contract does not quote its ADR statement")
        history = c.get("decisions") or []
        if not history or history[-1].get("statement_sha256") != sha(stmt):
            errors.append(f"{sid}: last decision does not record the current statement's sha256")
        for prev, cur in zip(history, history[1:]):
            if cur.get("previous_statement_sha256") != prev.get("statement_sha256"):
                errors.append(f"{sid}: decision history is not a chain")
        if set(c.get("witnesses", [])) != tests.get(sid, set()) or not tests.get(sid):
            errors.append(f"{sid}: witnesses {sorted(c.get('witnesses', []))} != tests saying "
                          f"'witness: {sid}' {sorted(tests.get(sid, []))}")
        for m in c.get("mutants", []):
            named.add(m)
            if m not in mutants or mutants[m]["statement"] != sid:
                errors.append(f"{sid}: mutant {m} missing or bound to another statement")
        if not c.get("mutants") and not c.get("mutation_exempt"):
            errors.append(f"{sid}: no mutant and no stated exemption")
    for path in CONTRACTS.glob("*.json"):
        if path.stem not in stmts:
            errors.append(f"{path.name}: contract for a statement no ADR makes")
    for sid in tests:
        if sid not in stmts:
            errors.append(f"tests witness {sid}, which no ADR states")
    for m in set(mutants) - named:
        errors.append(f"mutant {m} is named by no contract")
    for e in errors:
        print("FAIL", e)
    print(f"{len(stmts)} statements, {sum(len(v) for v in tests.values())} witness bindings, "
          f"{len(mutants)} mutants: {'FAIL' if errors else 'ok'}")
    return 1 if errors else 0


def suite(cwd):
    """(returncode, names of failing or erroring tests)."""
    proc = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests"],
                          cwd=cwd, capture_output=True, text=True)
    return proc.returncode, set(re.findall(r"^(?:FAIL|ERROR): (test_\w+)", proc.stderr, re.M))


def run_mutant(m):
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "repo"
        shutil.copytree(ROOT, work, ignore=shutil.ignore_patterns(".git", "__pycache__"))
        target = work / m["file"]
        text = target.read_text(encoding="utf-8")
        if text.count(m["find"]) != 1:
            return m["id"], "NOT_APPLIED"
        target.write_text(text.replace(m["find"], m["replace"]), encoding="utf-8")
        code, failed = suite(work)
        if code == 0:
            return m["id"], "SURVIVED", failed
        own = failed & witnesses_in_tests().get(m["statement"], set())
        return m["id"], "killed" if own else "OFF_TARGET", failed


def mutate(only=()):
    if suite(ROOT)[0] != 0:
        print("FAIL the unmutated suite does not pass")
        return 1
    mutants = [m for m in json.loads(MUTANTS.read_text(encoding="utf-8")) if not only or m["id"] in only]
    with ThreadPoolExecutor(4) as pool:
        results = list(pool.map(run_mutant, mutants))
    for (mid, outcome, failed), m in zip(results, mutants):
        print(f"{outcome:12} {mid:28} {m['statement']}  {m['why']}")
        if outcome == "OFF_TARGET":
            print(f"             failed only: {sorted(failed)}")
    bad = [r for r in results if r[1] != "killed"]
    print(f"{len(results) - len(bad)}/{len(results)} mutants killed")
    return 1 if bad else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "spec":
        SPEC.write_text(render_spec(), encoding="utf-8")
        print("wrote SPEC.md")
    elif cmd == "check":
        sys.exit(check())
    elif cmd == "mutate":
        sys.exit(mutate(sys.argv[2:]))
    else:
        sys.exit(__doc__)
